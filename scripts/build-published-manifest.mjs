#!/usr/bin/env node
/**
 * build-published-manifest — which articles and studies actually resolve.
 *
 *   node scripts/build-published-manifest.mjs           # write
 *   node scripts/build-published-manifest.mjs --check   # fail if stale
 *
 * WHY THIS EXISTS. The legacy redirect map names article-level destinations —
 * `/insights/news/gcc-it-hiring-trends-2026-cio-guide` goes to the renamed
 * article, not to the hub — because article-level authority is the thing worth
 * preserving. But an entry pointing at an article that is not published sends a
 * 301 into a 404, and passing authority to a dead page is worse for the legacy
 * estate than leaving the URL alone.
 *
 * Measured on 7 Aug 2026: none of the 21 insight articles are published
 * (`published: false` in every frontmatter), and three slugs in the case-study
 * map have no file at all. Every one of those destinations 404s today.
 *
 * Hand-editing those rows would be the instance fix, and it would rot the
 * moment Sumeet publishes an article. So the map resolves its destinations
 * against this manifest instead: published slug -> the article, otherwise the
 * hub. Publishing an article is then the only action needed; the redirect
 * follows on the next build.
 *
 * WHY GENERATED RATHER THAN READ AT RUNTIME. `src/middleware.ts` applies the
 * map, and middleware cannot read the filesystem. A generated module is bundled
 * with it, so the answer is available where the decision is made.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src/data/published.generated.mjs");

/** Slugs under content/<dir> whose frontmatter does not say published: false. */
function publishedSlugs(dir) {
  const base = join(ROOT, "content", dir);
  const out = [];
  for (const file of readdirSync(base)) {
    if (!file.endsWith(".mdx")) continue;
    const raw = readFileSync(join(base, file), "utf8");
    const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
    if (!match) continue;
    let frontmatter;
    try {
      frontmatter = parseYaml(match[1]);
    } catch {
      continue;
    }
    if (frontmatter?.published === false) continue;
    out.push(frontmatter?.slug ?? file.replace(/\.mdx$/, ""));
  }
  return out.sort();
}

const insights = publishedSlugs("insights");
const caseStudies = publishedSlugs("case-studies");

const list = (items) =>
  items.length === 0 ? "[]" : `[\n${items.map((s) => `  "${s}",`).join("\n")}\n]`;

const contents = `/**
 * GENERATED by scripts/build-published-manifest.mjs. Do not edit.
 *
 * The slugs that actually resolve, so the legacy redirect map can point at an
 * article when it exists and at the hub when it does not. Regenerate with
 * \`pnpm published:manifest\`; \`pnpm check:published-manifest\` fails when this
 * file and the content tree disagree.
 */

/** Insight articles without \`published: false\`. */
export const PUBLISHED_INSIGHTS = ${list(insights)};

/** Case studies without \`published: false\`. */
export const PUBLISHED_CASE_STUDIES = ${list(caseStudies)};
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    console.error(
      `\n${OUT} is missing. Run \`pnpm published:manifest\` and commit it.`,
    );
    process.exit(1);
  }
  if (current !== contents) {
    console.error(
      "\ncheck-published-manifest FAILED: src/data/published.generated.mjs does " +
        "not match the content tree.\n" +
        "  An article was published, unpublished, added or removed without " +
        "regenerating.\n  Run `pnpm published:manifest` and commit the result.",
    );
    process.exit(1);
  }
  console.log(
    `\nPublished manifest is current: ${insights.length} insight(s), ` +
      `${caseStudies.length} case study(ies).`,
  );
  process.exit(0);
}

writeFileSync(OUT, contents);
console.log(
  `Wrote ${OUT}\n  ${insights.length} published insight(s), ` +
    `${caseStudies.length} published case study(ies).`,
);
